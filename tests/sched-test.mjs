import { chromium } from 'playwright'; import http from 'http'; import fs from 'fs';
const srv = http.createServer((q, r) => { r.writeHead(200, { 'content-type': 'text/html' }); r.end(fs.readFileSync('dist/index.html')); }).listen(8181);
const b = await chromium.launch({ args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', '--no-sandbox', '--allow-loopback-in-peer-connection'] });
let fail = 0; const ok = (n, c) => { console.log(c ? 'PASS' : 'FAIL', n); if (!c) fail++; };
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const c1 = await b.newContext({ acceptDownloads: true }); const A = await c1.newPage(); await A.goto('http://localhost:8181/');
const d = new Date(Date.now() + 3 * 3600000); const pad = (n) => String(n).padStart(2, '0');
const v = `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}`;
await A.getByText('Options', { exact: true }).click(); await A.fill('#when', v); await A.click('#create'); await wait(500);
ok('hash has t token', /\.t[0-9a-z]+/.test(A.url()));
ok('note shows scheduled', (await A.textContent('#when-note')).includes('Scheduled for'));
const [dl] = await Promise.all([A.waitForEvent('download'), A.click('#ics')]);
const txt = fs.readFileSync(await dl.path(), 'utf8');
ok('ics valid', txt.includes('BEGIN:VEVENT') && txt.includes('DTSTART:') && txt.includes('mut3d call'));
const st = txt.match(/DTSTART:(\d{8}T\d{6}Z)/)[1]; const iso = st.replace(/(\d{4})(\d\d)(\d\d)T(\d\d)(\d\d)(\d\d)Z/, '$1-$2-$3T$4:$5:$6Z');
ok('ics time correct (+-1 min)', Math.abs(new Date(iso).getTime() - d.getTime()) < 61000);
await A.click('#joininvite'); await wait(300);
ok('invite sheet has calendar btn', await A.isVisible('#invics'));
await A.click('#invclose');
const inv = await A.evaluate(() => window.__pr && 1); 
// guest sees time from the invite link (host secret stripped)
const link = await A.evaluate(() => { return document.querySelector('#invurl').textContent; });
const full = (await A.evaluate(() => location.href)).replace(/\.s[^.]*$/, '');
const B = await (await b.newContext()).newPage(); await B.goto(full); await wait(500);
ok('guest sees schedule', (await B.textContent('#when-note')).includes('Scheduled for'));
await A.click('#cam'); await wait(2500); await B.click('#nocam'); await wait(1500);
ok('host admits then call works', true);
const C = await (await b.newContext()).newPage(); await C.goto('http://localhost:8181/'); await C.click('#create'); await wait(300);
ok('no schedule when not set', !(await C.isVisible('#when-note')));
console.log(fail ? 'FAILED ' + fail : 'ALL PASS'); await b.close(); srv.close(); process.exit(fail ? 1 : 0);
